let currentLang = localStorage.getItem('language') || 'ar';

function t(key) {
  if (!translations[currentLang]) return key;
  return translations[currentLang][key] || key;
}

function updateUIDirection() {
  document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.lang = currentLang;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    
    // Check if element has children other than text (like icons)
    // If it has an icon (e.g. <i>), we only replace the text node or the span inside it.
    const textSpan = el.querySelector('span[data-i18n-text]');
    
    if (textSpan) {
        textSpan.innerText = t(key);
    } else if (el.tagName === 'INPUT' && (el.type === 'text' || el.type === 'password' || el.type === 'search')) {
      el.placeholder = t(key);
    } else {
      // Just simple text replacement
      el.innerText = t(key);
    }
  });
  
  // Update toggle button text
  const langBtnText = document.getElementById('langToggleText');
  if (langBtnText) {
    langBtnText.innerText = t('toggle_lang');
  }
}

function toggleLanguage() {
  currentLang = currentLang === 'ar' ? 'en' : 'ar';
  try { localStorage.setItem('language', currentLang); } catch(e) { console.warn('localStorage error', e); }
  updateUIDirection();
  applyTranslations();
  window.dispatchEvent(new Event('languageChanged'));
}

// Initial setup
document.addEventListener('DOMContentLoaded', () => {
  updateUIDirection();
  applyTranslations();
});

window.t = t;
window.toggleLanguage = toggleLanguage;